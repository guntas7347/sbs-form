export function FAQSection() {
  const [searchQuery, setSearchQuery] = useState("");
  const [openIndex, setOpenIndex] = useState<number | null>(null);

  const filteredFaqs = faqs.filter(
    (faq) =>
      faq.question.toLowerCase().includes(searchQuery.toLowerCase()) ||
      faq.answer.toLowerCase().includes(searchQuery.toLowerCase()) ||
      faq.category.toLowerCase().includes(searchQuery.toLowerCase()),
  );

  return (
    <div className="w-full max-w-3xl mx-auto">
      {/* Search Bar */}
      <div className="relative mb-10 group">
        <Search className="absolute left-4 top-1/2 -translate-y-1/2 w-5 h-5 text-stone-400 group-focus-within:text-orange-500 transition-colors" />
        <input
          type="text"
          placeholder="Search questions, keywords, or topics..."
          value={searchQuery}
          onChange={(e) => setSearchQuery(e.target.value)}
          className="w-full pl-12 pr-4 py-4 rounded-2xl bg-white dark:bg-stone-900/40 border border-stone-200/80 dark:border-stone-800 focus:outline-none focus:ring-2 focus:ring-orange-500/20 dark:focus:ring-orange-500/20 focus:border-orange-500/50 dark:focus:border-orange-500/50 transition-all text-stone-900 dark:text-white shadow-sm"
        />
        {searchQuery && (
          <div className="absolute right-4 top-1/2 -translate-y-1/2 text-xs text-stone-400 font-medium">
            {filteredFaqs.length} results
          </div>
        )}
      </div>

      {/* FAQ Accordion */}
      <div className="space-y-3">
        {filteredFaqs.length > 0 ? (
          filteredFaqs.map((faq, index) => {
            const isOpen = openIndex === index;
            return (
              <div
                key={index}
                className={`overflow-hidden rounded-2xl border transition-all duration-200 ${
                  isOpen
                    ? "bg-white dark:bg-stone-900/60 border-orange-200/80 dark:border-stone-700 shadow-md"
                    : "bg-white/50 dark:bg-stone-900/20 border-stone-200/60 dark:border-stone-800/80 hover:border-stone-300 dark:hover:border-stone-700"
                }`}
              >
                <button
                  onClick={() => setOpenIndex(isOpen ? null : index)}
                  className="w-full text-left px-6 py-5 flex items-center justify-between gap-4 focus:outline-none"
                >
                  <div>
                    <span className="text-xs font-semibold tracking-wider text-orange-500 dark:text-orange-400 uppercase mb-1 block">
                      {faq.category}
                    </span>
                    <h3 className="text-base sm:text-lg font-semibold text-stone-900 dark:text-stone-100">
                      {faq.question}
                    </h3>
                  </div>
                  <div
                    className={`flex-shrink-0 w-8 h-8 rounded-full flex items-center justify-center transition-transform duration-200 ${
                      isOpen
                        ? "bg-orange-100 dark:bg-orange-900/30 text-orange-600 dark:text-orange-400 rotate-180"
                        : "bg-stone-100 dark:bg-stone-800 text-stone-500"
                    }`}
                  >
                    <ChevronDown className="w-4 h-4" />
                  </div>
                </button>

                <div
                  className={`px-6 transition-all duration-300 ease-in-out ${
                    isOpen ? "max-h-96 pb-6 opacity-100" : "max-h-0 opacity-0"
                  }`}
                >
                  <p className="text-stone-600 dark:text-stone-400 leading-relaxed text-sm sm:text-base border-t border-stone-100 dark:border-stone-800 pt-4">
                    {faq.answer}
                  </p>
                </div>
              </div>
            );
          })
        ) : (
          <div className="text-center py-16 px-6 rounded-2xl border border-dashed border-stone-300 dark:border-stone-800">
            <p className="text-stone-500 dark:text-stone-400">
              No results found for "{searchQuery}".
            </p>
            <button
              onClick={() => setSearchQuery("")}
              className="mt-4 text-orange-600 dark:text-orange-400 text-sm font-medium hover:underline"
            >
              Clear search
            </button>
          </div>
        )}
      </div>
    </div>
  );
}
